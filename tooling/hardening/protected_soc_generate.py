#!/usr/bin/env python3
"""Generate an encrypted, authenticated native SOC lookup table for Linux Release.

This relocates the 80 reference values from the Dart AOT snapshot into a
native OpenSSL AES-256-GCM lookup routine. Encryption is *at rest* only: a
local adversary can reverse the key derivation and extract the data.
"""
from __future__ import annotations

from pathlib import Path
import re
import secrets
import struct

from cryptography.hazmat.primitives.ciphers.aead import AESGCM

ROOT = Path(__file__).resolve().parents[2]
DART = ROOT / "soc_app/lib/domain/engine/soc_calculator.dart"
NATIVE = ROOT / "soc_app/linux/runner/protected_soc_table_generated.cc"
AAD = b"SOCShield.Table.V1"
TREATMENTS = ("F", "UNF")
EROSIONS = tuple(range(0, 80, 10))
DEPTHS = (10, 25, 35, 45, 55)


def parse_reference_data(source: str) -> list[int]:
    """Read the exact, existing Dart research reference table (cents of g/kg)."""
    treatment = None
    entries: dict[tuple[str, int, int], int] = {}
    for line in source.splitlines():
        top = re.match(r"\s*'(F|UNF)':\s*\{\s*$", line)
        if top:
            treatment = top.group(1)
            continue
        if treatment is None:
            continue
        data_line = re.match(r"^\s*(0|10|20|30|40|50|60|70):\s*\{(.*?)\},\s*$", line)
        if not data_line:
            continue
        erosion = int(data_line.group(1))
        matches = re.findall(r"\b(10|25|35|45|55):\s*(\d+\.\d{2})", data_line.group(2))
        if len(matches) != 5:
            raise ValueError(f"Incomplete reference row: {line}")
        for depth_text, decimal_text in matches:
            # Deterministic integer conversion (avoid float roundoff).
            major, fraction = decimal_text.split(".")
            value = int(major) * 100 + int(fraction)
            key = (treatment, erosion, int(depth_text))
            if key in entries:
                raise ValueError(f"Duplicate SOC entry: {key}")
            entries[key] = value
    expected = [(t, e, d) for t in TREATMENTS for e in EROSIONS for d in DEPTHS]
    missing = set(expected) - set(entries)
    extra = set(entries) - set(expected)
    if missing or extra:
        raise ValueError(f"Unexpected SOC table: missing={missing}, extra={extra}")
    return [entries[k] for k in expected]


def cpp_bytes(name: str, blob: bytes) -> str:
    lines = [f"  {', '.join(f'0x{b:02x}' for b in blob[i:i+12])},"
             for i in range(0, len(blob), 12)]
    return f"static const unsigned char {name}[{len(blob)}] = {{\n" + "\n".join(lines) + "\n};"


def render_native(values: list[int], key: bytes, nonce: bytes, mask: bytes) -> str:
    if len(values) != 80:
        raise ValueError("80 values required")
    clear = struct.pack("<80H", *values)
    cipher_and_tag = AESGCM(key).encrypt(nonce, clear, AAD)
    cipher, tag = cipher_and_tag[:-16], cipher_and_tag[-16:]
    masked_key = bytes(a ^ b for a, b in zip(key, mask))
    blocks = "\n\n".join([
        cpp_bytes("kProtectedCiphertext", cipher),
        cpp_bytes("kProtectedTag", tag),
        cpp_bytes("kProtectedNonce", nonce),
        cpp_bytes("kKeyMask", mask),
        cpp_bytes("kMaskedKey", masked_key)
    ])
    return '''// Generated by tooling/hardening/protected_soc_generate.py.
// DO NOT edit; contains AES-GCM ciphertext and client-side key material.
// This raises reverse-engineering cost; it is not a secrecy boundary.
#include <openssl/crypto.h>
#include <openssl/evp.h>
#include <cstddef>
#include <cstdint>
#include <limits>
#include <cmath>

namespace {
''' + blocks + '''
static const unsigned char kAad[] = "SOCShield.Table.V1";
}

#if defined(__GNUC__)
#define SOC_API extern "C" __attribute__((visibility("default")))
#else
#define SOC_API extern "C"
#endif

SOC_API double soc_data_access(int treatment, int erosion, int depth) {
  if (treatment < 0 || treatment > 1 || erosion < 0 || erosion > 70 ||
      erosion % 10 != 0) {
    return std::numeric_limits<double>::quiet_NaN();
  }
  int depth_index = -1;
  switch (depth) {
    case 10: depth_index = 0; break;
    case 25: depth_index = 1; break;
    case 35: depth_index = 2; break;
    case 45: depth_index = 3; break;
    case 55: depth_index = 4; break;
    default: return std::numeric_limits<double>::quiet_NaN();
  }
  const int index = (treatment * 8 + (erosion / 10)) * 5 + depth_index;
  unsigned char key[32] = {0};
  unsigned char plaintext[sizeof(kProtectedCiphertext)] = {0};
  for (std::size_t i = 0; i < sizeof(key); ++i) {
    key[i] = kKeyMask[i] ^ kMaskedKey[i];
  }
  EVP_CIPHER_CTX* ctx = EVP_CIPHER_CTX_new();
  bool good = ctx != nullptr;
  int count = 0;
  int written = 0;
  if (good) good = EVP_DecryptInit_ex(ctx, EVP_aes_256_gcm(), nullptr,
                                      nullptr, nullptr) == 1;
  if (good) good = EVP_CIPHER_CTX_ctrl(ctx, EVP_CTRL_GCM_SET_IVLEN,
                                       sizeof(kProtectedNonce), nullptr) == 1;
  if (good) good = EVP_DecryptInit_ex(ctx, nullptr, nullptr, key,
                                      kProtectedNonce) == 1;
  if (good) good = EVP_DecryptUpdate(ctx, nullptr, &count, kAad,
                                      sizeof(kAad) - 1) == 1;
  if (good) good = EVP_DecryptUpdate(ctx, plaintext, &written,
                                      kProtectedCiphertext,
                                      sizeof(kProtectedCiphertext)) == 1;
  if (good) good = EVP_CIPHER_CTX_ctrl(ctx, EVP_CTRL_GCM_SET_TAG,
                                       sizeof(kProtectedTag),
                                       const_cast<unsigned char*>(kProtectedTag)) == 1;
  if (good) good = EVP_DecryptFinal_ex(ctx, plaintext + written, &count) == 1;
  if (ctx != nullptr) EVP_CIPHER_CTX_free(ctx);
  double answer = std::numeric_limits<double>::quiet_NaN();
  if (good && written + count == static_cast<int>(sizeof(plaintext))) {
    const auto lo = static_cast<unsigned>(plaintext[2 * index]);
    const auto hi = static_cast<unsigned>(plaintext[2 * index + 1]);
    answer = static_cast<double>(lo | (hi << 8)) / 100.0;
  }
  OPENSSL_cleanse(key, sizeof(key));
  OPENSSL_cleanse(plaintext, sizeof(plaintext));
  return answer;
}
'''


def generate(output: Path = NATIVE) -> list[int]:
    values = parse_reference_data(DART.read_text(encoding="utf-8"))
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(render_native(values, secrets.token_bytes(32),
                                    secrets.token_bytes(12),
                                    secrets.token_bytes(32)), encoding="utf-8")
    return values


if __name__ == "__main__":
    generate()
    print("Generated authenticated native table from 80 source fixtures")
